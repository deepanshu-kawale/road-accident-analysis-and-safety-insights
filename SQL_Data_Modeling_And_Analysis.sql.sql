CREATE TABLE ACCIDENT (ID VARCHAR(50) PRIMARY KEY,SEVERITY INT,
START_TIME DATETIME,END_TIME DATETIME,DISTANCE DECIMAL(10,2));

CREATE TABLE LOCATION (ID VARCHAR(50) PRIMARY KEY,START_LAT DECIMAL(10,6),
START_LNG DECIMAL(10,6),STREET VARCHAR(255),CITY VARCHAR(100),
DISTRICT VARCHAR(100),STATE VARCHAR(100),
FOREIGN KEY (ID)REFERENCES ACCIDENT(ID));
    
CREATE TABLE WEATHER (ID VARCHAR(50) PRIMARY KEY,TEMPERATURE DECIMAL(5,2),
HUMIDITY DECIMAL(5,2),VISIBILITY DECIMAL(5,2),WIND_SPEED DECIMAL(5,2),
WEATHER_CONDITION VARCHAR(100),SUNRISE_SUNSET VARCHAR(50),
FOREIGN KEY (ID)REFERENCES ACCIDENT(ID));
    
CREATE TABLE ROAD_FEATURES (ID VARCHAR(50) PRIMARY KEY,CROSSING BOOL,
JUNCTION BOOL,STOP BOOL,TRAFFIC_SIGNAL BOOL,
FOREIGN KEY (ID)REFERENCES ACCIDENT(ID));
    
