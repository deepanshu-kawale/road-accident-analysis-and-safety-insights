## Top 5 City Wise Accident Count
SELECT L.CITY, COUNT(A.ID) AS ACCIDENT_COUNT FROM ACCIDENT A INNER JOIN LOCATION L 
ON A.ID= L.ID GROUP BY L.CITY ORDER BY COUNT(A.ID) DESC LIMIT 5;

## Top 5 States with Highest Accident Count and Average Severity
SELECT L.STATE, AVG(A.SEVERITY) AS AVG_SEVERITY, COUNT(A.ID) AS ACCIDENT_COUNT 
FROM ACCIDENT A INNER JOIN LOCATION L ON A.ID= L.ID
GROUP BY L.STATE ORDER BY ACCIDENT_COUNT DESC LIMIT 5;


## Top 5 Weather Conditions with Highest Accident Count and Average Severity
SELECT W.WEATHER_CONDITION, COUNT(A.ID) AS ACCIDENT_COUNT, AVG(SEVERITY) AS AVG_SEVERITY 
FROM WEATHER W INNER JOIN ACCIDENT A ON W.ID=A.ID GROUP BY WEATHER_CONDITION ORDER BY 
ACCIDENT_COUNT DESC LIMIT 5;

## Top 5 High-Risk City and Weather Condition Combinations by Accident Count
SELECT L.CITY, W.WEATHER_CONDITION, W.SUNRISE_SUNSET, AVG(A.SEVERITY) AS AVG_SEVERITY ,
COUNT(A.ID) AS HIGH_ACCIDENTS  FROM ACCIDENT A INNER JOIN LOCATION L ON A.ID=L.ID
INNER JOIN WEATHER W ON A.ID=W.ID GROUP BY L.CITY,W.WEATHER_CONDITION ,
W.SUNRISE_SUNSET ORDER BY HIGH_ACCIDENTS DESC LIMIT 5;

## Top 10 High-Risk Districts with High Humidity and Low Visibility Conditions
SELECT L.DISTRICT, W.HUMIDITY, W.VISIBILITY, COUNT(A.ID) AS HIGH_ACCIDENT
FROM ACCIDENT A INNER JOIN LOCATION L ON A.ID=L.ID INNER JOIN WEATHER W 
ON A.ID=W.ID WHERE W.HUMIDITY > 70 AND W.VISIBILITY < 5 GROUP BY
L.DISTRICT, W.HUMIDITY, W.VISIBILITY ORDER BY HIGH_ACCIDENT DESC LIMIT 10;






    